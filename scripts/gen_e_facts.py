#!/usr/bin/env python3
"""GEN-E factual read (docs/reports/GEN_E_CONTENT_PLAN.md, read 4), fixed before any planned text was read.

For every covered prompt (a PLAN line with facts in PLANFILE), in each generated text (GEN lines of SAMPLEFILE, which
must use the same prompt ids): a statement is a frame connective of a relation the entity has in its plan, followed
by a value the model wrote. It is consistent if the value is the plan's value, else a contradiction.

Connectives: the bytes between the subject and the value in F2's frames (patterns.tsv; raw frames from F2R), markup
dropped, lowercased; kept if they hold a word of 4 or more letters. Frames as the plan builds them (A3: at most 3
per relation in each file). One statement per relation and value position. A connective that frames several relations goes
to the relation with the most training subjects for it (F2's own count); ties are dropped. Values: for a year relation
the first 3-4 digit number within 40 bytes (before a sentence end); otherwise A3's head rule: the bytes before the
first , . ; ( ) | or newline, at most 5 words, one capitalised. Only values that start inside the generated bytes
count. A second count also needs a word (3+ letters, capitalised) of the entity's title in the 60 bytes before.

usage: gen_e_facts.py PLANFILE PATTERNS RAWPATTERNS SAMPLEFILE [SAMPLEFILE...]
"""
import random
import re
import sys

YEAR_RELS = {"birth_year", "death_year", "founded"}


def unescape(s):
    s = s.replace("\\n", "\n")
    b = re.sub(r"\\x([0-9a-f]{2})", lambda m: chr(int(m.group(1), 16)), s)
    return b.encode("latin-1", "replace").decode("utf-8", "replace")


def strip_markup(t):
    out, i = [], 0
    while i < len(t):
        if t.startswith("'''", i):
            i += 3
        elif t.startswith("''", i) or t.startswith("[[", i) or t.startswith("]]", i):
            i += 2
        else:
            out.append(" " if t[i] == "|" else t[i])
            i += 1
    return "".join(out)


def norm(s):
    s = strip_markup(s)
    for a, b in ((" ( ", " ("), (" , ", ", "), (" ' s", "'s"), (" .", "."), (" :", ":")):
        s = s.replace(a, b)
    return re.sub(r"\s+", " ", s).lower()


def connectives(paths):
    """The plan's frames (A3's load_frames: per file, kept patterns first then by training subjects, at most 3 a
    relation), their connectives, each given to the relation with the most training subjects for it."""
    best = {}  # connective -> {relation: training subjects}
    for path in paths:
        by = {}
        for line in open(path, encoding="utf-8", errors="replace"):
            f = line.rstrip("\n").split("\t")
            if len(f) < 11 or f[0] == "relation":
                continue
            raw = len(f) >= 12 and f[11] != ""
            p = f[11] if raw else f[1]
            subj = [x for x in (p.find("[S]"), p.find("[P]")) if x >= 0]
            obj = p.find("[O]")
            if not subj or obj < 0 or obj < min(subj) or "<M>" in p or "#" in p:
                continue
            by.setdefault(f[0], []).append((-int(f[10] or 0), -int(f[2] or 0), p))
        for rel0, v in by.items():
            v.sort()
            seen = []
            for k, n, p in v:
                if len(seen) >= 3 or p in seen:
                    continue
                seen.append(p)
                last = max(x for x in (p.rfind("[S]"), p.rfind("[P]")) if x >= 0)
                c = norm(p[last + 3:p.find("[O]")]).strip().rstrip("[").strip()
                if not re.search(r"[a-z]{4}", c):
                    continue
                rel = {"birth_date": "birth_year", "death_date": "death_year"}.get(rel0, rel0)
                d = best.setdefault(c, {})
                d[rel] = max(d.get(rel, 0), -n)
    out = {}
    for c, d in best.items():
        top = max(d.values())
        rels = [r for r, n in d.items() if n == top]
        if len(rels) == 1:
            out.setdefault(rels[0], set()).add(c)
    return out


def fold(s):
    s = re.sub(r"\s+", " ", strip_markup(s).lower()).strip()
    return s.strip(" .,;:'\"")


def same(cand, value, year):
    if year:
        return re.sub(r"\D", "", cand) == re.sub(r"\D", "", value)
    a, b = fold(cand), fold(value)
    if a == b:
        return True
    short, long_ = (a, b) if len(a) <= len(b) else (b, a)
    return len(short) >= 4 and long_.startswith(short + " ")


def value_after(text, k, year):
    rest = text[k:k + 200]
    if year:
        m = re.search(r"(?<!\d)(\d{3,4})(?!\d)", rest[:40])
        if not m:
            return None
        if re.search(r"\.\s|\n", rest[:m.start()]):
            return None
        return k + m.start(), m.group(1)
    m = re.search(r"[,.;()|\n]", rest)
    head = rest[:m.start()] if m else rest
    v = head.strip()
    ws = v.split()
    if not v or len(ws) > 5 or not any(w[:1].isupper() for w in ws):
        return None
    return k + (len(head) - len(head.lstrip())), v


def statements(prompt, gen, entity, facts, conn):
    text = strip_markup(prompt + gen)
    start = len(strip_markup(prompt))
    low = text.lower()
    words = [w for w in re.findall(r"[A-Za-z]{3,}", entity) if w[:1].isupper()]
    out, seen = [], set()
    for rel, value in facts:
        year = rel in YEAR_RELS
        for c in conn.get(rel, ()):
            for m in re.finditer(re.escape(c), low):
                if m.start() > 0 and c[:1].isalpha() and low[m.start() - 1].isalpha():
                    continue
                v = value_after(text, m.end(), year)
                if not v or v[0] < start or (rel, v[0]) in seen:
                    continue
                seen.add((rel, v[0]))
                bound = any(w in text[max(0, m.start() - 60):m.start()] for w in words)
                out.append((rel, v[1], same(v[1], value, year), bound))
    return out


def read(path):
    rows, cur = {}, None
    for line in open(path, encoding="utf-8", errors="replace"):
        f = line.rstrip("\n").split("\t")
        if f[0] == "PROMPT":
            cur = int(f[1])
            rows[cur] = {"prompt": unescape(f[2]), "gens": {}, "plan": None}
        elif f[0] == "PLAN" and cur is not None:
            facts = [tuple(x.split("=", 1)) for x in f[3].split("|")] if len(f) > 3 and f[3] else []
            rows[cur]["plan"] = (unescape(f[2]), [(r, unescape(v)) for r, v in facts])
        elif f[0] == "GEN" and cur is not None:
            rows[cur]["gens"][f[1]] = unescape(f[2])
    return rows


def wilson(k, n, z=1.96):
    if n == 0:
        return (0.0, 0.0, 0.0)
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * ((p * (1 - p) / n + z * z / (4 * n * n)) ** 0.5) / d
    return (p, c - h, c + h)


def main():
    planfile, pat, raw, samples = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4:]
    conn = connectives([pat, raw])
    print("connectives:", "; ".join(f"{r}: {sorted(c)}" for r, c in sorted(conn.items())))
    plans = {i: r["plan"] for i, r in read(planfile).items() if r["plan"] and r["plan"][1]}
    print(f"covered prompts {len(plans)}")
    per = {}
    for path in samples:
        rows = read(path)
        tot = {"texts": 0, "st": 0, "ok": 0, "bad": 0, "bst": 0, "bok": 0, "bbad": 0, "expressed": 0, "facts": 0}
        by_prompt = []
        rels = {}
        for i, (entity, facts) in sorted(plans.items()):
            if i not in rows:
                continue
            pk = [0, 0]
            for kind, gen in rows[i]["gens"].items():
                tot["texts"] += 1
                g = fold(gen)
                for rel, value in facts:
                    tot["facts"] += 1
                    tot["expressed"] += fold(value) in g if fold(value) else 0
                for rel, v, ok, bound in statements(rows[i]["prompt"], gen, entity, facts, conn):
                    tot["st"] += 1
                    tot["ok" if ok else "bad"] += 1
                    pk[0 if ok else 1] += 1
                    r = rels.setdefault(rel, [0, 0])
                    r[0 if ok else 1] += 1
                    if bound:
                        tot["bst"] += 1
                        tot["bok" if ok else "bbad"] += 1
            by_prompt.append(pk)
        per[path] = by_prompt
        p, lo, hi = wilson(tot["ok"], tot["st"])
        print(f"\n{path}\n  texts {tot['texts']} statements {tot['st']} consistent {tot['ok']} contradictions {tot['bad']}"
              f" precision {p:.3f} [{lo:.3f}, {hi:.3f}]")
        print(f"  subject-bound: statements {tot['bst']} consistent {tot['bok']} contradictions {tot['bbad']}")
        e, el, eh = wilson(tot["expressed"], tot["facts"])
        print(f"  planned values written anywhere in the text: {tot['expressed']} of {tot['facts']} ({e:.3f} [{el:.3f}, {eh:.3f}])")
        print("  by relation (consistent, contradictions):", dict(sorted(rels.items())))
    if len(samples) == 2:  # paired bootstrap over prompts: change in consistent and contradicting statements
        a, b = per[samples[0]], per[samples[1]]
        rng = random.Random(20261029)
        n = len(a)
        for j, name in ((0, "consistent"), (1, "contradictions")):
            d = sum(x[j] for x in b) - sum(x[j] for x in a)
            boots = []
            for _ in range(2000):
                idx = [rng.randrange(n) for _ in range(n)]
                boots.append(sum(b[k][j] - a[k][j] for k in idx))
            boots.sort()
            print(f"\nchange in {name} (second - first): {d:+d} [{boots[49]:+d}, {boots[1949]:+d}] (paired bootstrap over prompts)")


if __name__ == "__main__":
    main()
